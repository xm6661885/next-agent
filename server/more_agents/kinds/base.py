"""Each adapter owns native I/O; the runtime owns local turns and prompts."""
from typing import Protocol

class TurnError(Exception): pass
class TurnEnded(Exception): pass

class Adapter(Protocol):
    closed: object  # Future, resolved when the native connection closes
    @property
    def connected(self) -> bool: ...
    async def connect(self) -> None: ...
    async def run_turn(self, text, attachments) -> object: ...  # terminal result Future
    async def steer(self, text, attachments) -> None: ...
    async def interrupt(self) -> None: ...
    async def set_option(self, id, value) -> None: ...
    async def set_mode(self, id) -> None: ...
    async def disconnect(self) -> None: ...

class Kind(Protocol):
    capabilities: dict
    def adapter(self, runtime) -> Adapter: ...
    async def test(self, agent) -> dict: ...
    async def models(self, agent) -> list: ...
    async def shutdown(self) -> None: ...
