"""Small adapter contracts shared by More Agents kinds."""
from typing import Protocol

class Adapter(Protocol):
    async def connect(self, session): ...
    async def run_turn(self, text, attachments=()): ...
    async def steer(self, text, attachments=()): ...
    async def interrupt(self): ...
    async def set_option(self, id, value): ...
    async def set_mode(self, id): ...
    async def reply_permission(self, native_id, option): ...
    async def reply_question(self, native_id, answers): ...
    async def disconnect(self): ...

class Kind(Protocol):
    def test(self, agent): ...
    def models(self, agent): ...
    async def shutdown(self): ...
